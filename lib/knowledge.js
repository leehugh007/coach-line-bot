/**
 * 從用戶訊息和聊天歷史中取得相關知識注入文字
 * Phase 1：AI 意圖分類（主要）+ regex 降級備案
 *
 * @param {string} userText - 當前用戶訊息
 * @param {Array} chatHistory - 聊天歷史（Gemini 格式）
 * @returns {string} 要注入到 System Prompt 的知識文字
 */
export async function getRelevantKnowledge(userText, chatHistory = []) {
  let matched = [];

  // 嘗試 AI 意圖分類
  const intent = await classifyIntent(userText);

  if (intent?.tags?.length > 0) {
    // AI 分類成功：用 tags 匹配知識塊
    matched = TIER2_BLOCKS
      .filter(block => block.tags.some(t => intent.tags.includes(t)))
      .slice(0, 2);
    console.log(`[Knowledge] AI matched: ${matched.map(b => b.id).join(', ') || 'none'}`);
  }

  // 降級備案：AI 沒匹配到或失敗時，用 regex
  if (matched.length === 0) {
    const recentTexts = chatHistory
      .filter(msg => msg.role === 'user')
      .map(msg => msg.parts?.[0]?.text || '')
      .join(' ');
    const searchText = `${userText} ${recentTexts}`;

    matched = TIER2_BLOCKS
      .filter(block => block.keywords.test(searchText))
      .slice(0, 2);

    if (matched.length > 0) {
      console.log(`[Knowledge] Regex fallback matched: ${matched.map(b => b.id).join(', ')}`);
    }
  }

  // 組合結果
  let knowledge = TIER1_SUMMARY;

  if (matched.length > 0) {
    knowledge += '\n' + matched.map(b => b.content).join('\n');
  }

  return knowledge;
}
