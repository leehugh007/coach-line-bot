/**
 * 用 AI 分類用戶訊息的意圖，回傳相關知識標籤
 * @param {string} userText - 用戶訊息
 * @returns {{ tags: string[], mood: string } | null}
 */
async function classifyIntent(userText) {
  try {
    const res = await fetch(getClassifierUrl(), {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        contents: [{
          role: 'user',
          parts: [{ text: `${INTENT_PROMPT}\n\n用戶訊息：「${userText}」` }],
        }],
        generationConfig: {
          temperature: 0.1,
          maxOutputTokens: 60,
        },
      }),
    });

    if (!res.ok) {
      console.error('[Intent] Gemini error:', res.status);
      return null;
    }

    const data = await res.json();
    const raw = data.candidates?.[0]?.content?.parts?.[0]?.text || '';
    const jsonMatch = raw.match(/\{[\s\S]*?\}/);
    if (!jsonMatch) {
      console.error('[Intent] No JSON:', raw);
      return null;
    }

    const result = JSON.parse(jsonMatch[0]);
    console.log(`[Intent] "${userText.substring(0, 30)}..." → tags=${result.tags?.join(',')}, mood=${result.mood}`);
    return result;
  } catch (err) {
    console.error('[Intent] Error:', err.message);
    return null;
  }
}

