/**
 * 用 AI 分類用戶訊息的意圖，回傳相關知識標籤
 * @param {string} userText - 用戶訊息
 * @param {string} recentContext - 最近的用戶訊息上下文（選填）
 * @returns {{ tags: string[], mood: string, slices: string[] } | null}
 */
export async function classifyIntent(userText, recentContext = '') {
  try {
    // 組合訊息：當前訊息 + 最近上下文（讓分類器看到完整脈絡）
    const contextText = recentContext
      ? `（前文：${recentContext}）\n當前訊息：「${userText}」`
      : `「${userText}」`;

    console.log(`[Intent] Calling classifier for: "${userText.substring(0, 40)}..."`);
    const res = await fetch(getClassifierUrl(), {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        contents: [{
          role: 'user',
          parts: [{ text: `${INTENT_PROMPT}\n\n用戶訊息：${contextText}` }],
        }],
        generationConfig: {
          temperature: 0.1,
          maxOutputTokens: 100,
        },
      }),
    });

    if (!res.ok) {
      console.error('[Intent] Gemini error:', res.status);
      return null;
    }

    const data = await res.json();
    const raw = data.candidates?.[0]?.content?.parts?.[0]?.text || '';
    const jsonMatch = raw.match(/\{[\s\S]*?\}/);
    if (!jsonMatch) {
      console.error('[Intent] No JSON:', raw);
      return null;
    }

    const result = JSON.parse(jsonMatch[0]);
    console.log(`[Intent] "${userText.substring(0, 30)}..." → tags=${result.tags?.join(',')}, mood=${result.mood}, slices=${result.slices?.join(',') || 'none'}`);
    return result;
  } catch (err) {
    console.error('[Intent] Error:', err.message);
    return null;
  }
}

